"""Generated 68k lookup tables indexed by the CPS1 layer-control order byte (lc >> 6)."""


def prictrl(v):
    order = [(v >> (2 * i)) & 3 for i in range(4)]   # bottom first
    pri, lvl = 0, 1
    for lid in order:
        if lid == 0:
            lvl = max(lvl, 4)
            continue
        pri |= (lvl & 0xF) << (4 * lid)
        lvl += 1
    return pri & 0xFFFF


def below(v):
    """Layer id directly below the sprite slot (0 = sprites at the bottom / absent)."""
    order = [(v >> (2 * i)) & 3 for i in range(4)]
    if 0 not in order:
        return 0
    i = order.index(0)
    return order[i - 1] if i > 0 else 0


def asm():
    pri = [prictrl(v) for v in range(256)]
    bel = [below(v) for v in range(256)]
    out = ["; generated by cps15to2/tables.py", "        even", "prictrl_table:"]
    for i in range(0, 256, 8):
        out.append("        dc.w    " + ", ".join(f"${x:04x}" for x in pri[i:i + 8]))
    out.append("below_table:")
    for i in range(0, 256, 16):
        out.append("        dc.b    " + ", ".join(str(x) for x in bel[i:i + 16]))
    out.append("        even")
    return "\n".join(out) + "\n"
