"""Insert / update the 18 conversion entries in ~/mame (cps2.cpp + mame.lst).

The block is delimited by markers and regenerated from out/mame/*/rom_start.inc,
so driver CRCs always match the converter output. Only lines between the markers
are ever touched.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from cps15to2.sets import SETS  # noqa: E402

MAME = Path.home() / "mame"
DRV = MAME / "src/mame/capcom/cps2.cpp"
LST = MAME / "src/mame/mame.lst"
OUT = Path(__file__).resolve().parents[1] / "out/mame"
B1, E1 = "// BEGIN CPS15_TO_CPS2 conversions (generated by CPS15_to_CPS2/tools/mame_driver.py)", "// END CPS15_TO_CPS2 conversions"
B2, E2 = "// BEGIN CPS15_TO_CPS2 GAME entries", "// END CPS15_TO_CPS2 GAME entries"

INPUTS = """
// 3 players and 2 buttons (WoF / C&D conversions) - same pins as cps2_3p3b (AvP harness)
static INPUT_PORTS_START( cps2_3p2b_c2 )
	PORT_INCLUDE(cps2_3p3b)

	PORT_MODIFY("IN0")
	PORT_BIT( 0x0040, IP_ACTIVE_LOW, IPT_UNUSED ) // BUTTON3 PORT_PLAYER(1)
	PORT_BIT( 0x4000, IP_ACTIVE_LOW, IPT_UNUSED ) // BUTTON3 PORT_PLAYER(2)

	PORT_MODIFY("IN1")
	PORT_BIT( 0x0040, IP_ACTIVE_LOW, IPT_UNUSED ) // BUTTON3 PORT_PLAYER(3)
INPUT_PORTS_END
"""


def _replace_block(text, begin, end, body, anchor_before):
    pat = re.compile(re.escape(begin) + ".*?" + re.escape(end) + "\n", re.S)
    block = begin + "\n" + body + end + "\n"
    if pat.search(text):
        return pat.sub(lambda m: block, text)
    i = text.index(anchor_before)
    return text[:i] + block + "\n" + text[i:]


def placeholder(name):
    """ROM_START with the fixed conversion layout and unknown CRCs (set not built yet).
    MAME runs such a set with a checksum warning, so the driver need not be rebuilt
    every time a conversion changes."""
    z = "CRC(00000000) SHA1(0000000000000000000000000000000000000000)"
    lines = [f"ROM_START( {name} )", '\tROM_REGION( CODE_SIZE, "maincpu", 0 ) // 68000 code']
    for i in range(7):
        lines.append(f'\tROM_LOAD16_WORD_SWAP( "{name}.{i + 3:02d}", 0x{i * 0x80000:06x}, 0x80000, {z} )')
    lines += ["", '\tROM_REGION( 0x1000000, "gfx", 0 )']
    for i, n in enumerate(("13m", "15m", "17m", "19m")):
        lines.append(f'\tROM_LOAD64_WORD( "{name}.{n}", 0x{i * 2:07x}, 0x400000, {z} )')
    lines += ["", '\tROM_REGION( QSOUND_SIZE, "audiocpu", 0 ) // 64k for the audio CPU (+banks)',
              f'\tROM_LOAD( "{name}.01", 0x00000, 0x08000, {z} )', "\tROM_CONTINUE(         0x10000, 0x18000 )", "",
              '\tROM_REGION( 0x400000, "qsound", 0 ) // QSound samples',
              f'\tROM_LOAD16_WORD_SWAP( "{name}.11m", 0x000000, 0x400000, {z} )', "",
              '\tROM_REGION( 0x20, "key", 0 )',
              '\tROM_LOAD( "phoenix.key", 0x000000, 0x000014, CRC(2cf772b0) SHA1(eff33c65a4f3862c231f9e4d6fefa7b34398dbf2) )',
              "ROM_END", ""]
    return "\n".join(lines)


def main(names=None):
    names = names or [s.name for s in SETS.values()]
    roms, games = [INPUTS], []
    for info in SETS.values():
        inc = OUT / info.name / "rom_start.inc"
        if info.name not in names:
            continue
        roms.append(inc.read_text() if inc.exists() else placeholder(info.name))
        inputs = info.mame_inputs if info.mame_inputs != "cps2_3p2b" else "cps2_3p2b_c2"
        parent = info.parent or "0"
        games.append(f'GAME( {info.year}, {info.name + ",":<13} {parent + ",":<12} dead_cps2, {inputs + ",":<14} cps2_state, init_cps2, ROT0, '
                     f'"Capcom", "{info.desc} (CPS2 conversion)", MACHINE_SUPPORTS_SAVE )')
    text = DRV.read_text()
    text = _replace_block(text, B1, E1, "\n".join(roms), "} // anonymous namespace")
    text = text.rstrip("\n") + "\n"
    pat = re.compile(re.escape(B2) + ".*?" + re.escape(E2) + "\n", re.S)
    blk = B2 + "\n" + "\n".join(games) + "\n" + E2 + "\n"
    text = pat.sub(lambda m: blk, text) if pat.search(text) else text + "\n" + blk
    DRV.write_text(text)
    # mame.lst: add names after the cps2 source line if missing
    lst = LST.read_text().splitlines()
    i = lst.index("@source:capcom/cps2.cpp")
    j = i + 1
    while j < len(lst) and lst[j].strip():
        j += 1
    existing = set(lst[i + 1:j])
    new = [n for n in names if n not in existing]
    lst[j:j] = new
    LST.write_text("\n".join(lst) + "\n")
    print(f"{len(games)} GAME entries, {len(new)} added to mame.lst")


if __name__ == "__main__":
    main(sys.argv[1:] or None)
